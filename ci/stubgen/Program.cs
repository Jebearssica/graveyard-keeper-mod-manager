using System.Text;
using Mono.Cecil;
using Mono.Cecil.Cil;

// Regenerates the compile-only API stubs under ci/refs from a built plugin:
//
//   dotnet run --project ci/stubgen -c Release -- \
//       src/bin/Release/GKModManager.dll ci/refs "<game>/Graveyard Keeper_Data/Managed" \
//       Assembly-CSharp Assembly-CSharp-firstpass
//
// The plugin's IL is walked to find every type and member it links against in the game
// assemblies; only those are emitted, as declaration-only C#. That lets CI compile the
// plugin on a machine with no game install, without shipping any game bytes.

internal static class Program
{
    private static readonly HashSet<string> Targets = new(StringComparer.Ordinal);

    private static int Main(string[] args)
    {
        if (args.Length < 4)
        {
            Console.Error.WriteLine("usage: stubgen <plugin.dll> <outDir> <managedDir> <assembly>...");
            return 2;
        }

        var pluginPath = Path.GetFullPath(args[0]);
        var outDir = Path.GetFullPath(args[1]);
        var searchDir = Path.GetFullPath(args[2]);
        for (var i = 3; i < args.Length; i++) Targets.Add(args[i]);

        var resolver = new DefaultAssemblyResolver();
        resolver.AddSearchDirectory(searchDir);
        resolver.AddSearchDirectory(Path.GetDirectoryName(pluginPath));

        using var module = ModuleDefinition.ReadModule(
            pluginPath, new ReaderParameters { AssemblyResolver = resolver });

        var types = new HashSet<TypeDefinition>(DefinitionComparer<TypeDefinition>.Instance);
        var methods = new HashSet<MethodDefinition>(DefinitionComparer<MethodDefinition>.Instance);
        var fields = new HashSet<FieldDefinition>(DefinitionComparer<FieldDefinition>.Instance);

        foreach (var type in module.Types) WalkType(type, types, methods, fields);

        // Follow declaring types, base types and interfaces so member lookups resolve the way
        // they do against the real assemblies. Signatures of the plugin's own members were
        // already followed above; recursing through every member of a stubbed type would pull
        // in the whole game.
        var queue = new Queue<TypeDefinition>(types);
        while (queue.Count > 0)
        {
            var t = queue.Dequeue();
            if (t.DeclaringType != null) Consider(t.DeclaringType, types, methods, fields, queue);
            if (t.BaseType != null) Consider(t.BaseType, types, methods, fields, queue);
            foreach (var i in t.Interfaces) Consider(i.InterfaceType, types, methods, fields, queue);
        }

        Directory.CreateDirectory(outDir);
        foreach (var target in Targets.OrderBy(t => t, StringComparer.Ordinal))
        {
            var own = types
                .Where(t => string.Equals(t.Module.Assembly.Name.Name, target, StringComparison.Ordinal))
                .ToList();
            var topLevel = own.Where(t => !t.IsNested)
                .OrderBy(t => t.FullName, StringComparer.Ordinal)
                .ToList();

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Compile-only declaration stubs for " + target + ".");
            sb.AppendLine("// Generated by ci/stubgen from the members this plugin links against: no game code,");
            sb.AppendLine("// only the API shape. Regenerate after adding calls to new game APIs.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine("#pragma warning disable CS0067, CS0108, CS0114, CS0169, CS0649, CS1591");
            sb.AppendLine();

            var namespaces = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var t in own) AddNamespace(namespaces, t.BaseType);

            foreach (var ns in namespaces.Where(n => n.Length > 0)) sb.AppendLine("using " + ns + ";");
            if (namespaces.Count > 0) sb.AppendLine();

            foreach (var t in topLevel)
            {
                EmitTopLevel(sb, t, types, methods, fields);
                sb.AppendLine();
            }

            var targetDir = Path.Combine(outDir, target);
            Directory.CreateDirectory(targetDir);
            File.WriteAllText(Path.Combine(targetDir, target + ".Stub.cs"), sb.ToString(), new UTF8Encoding(false));

            var memberCount = own.Sum(t => t.Methods.Count(methods.Contains) + t.Fields.Count(fields.Contains));
            Console.WriteLine($"{target}: {topLevel.Count} types (+{own.Count - topLevel.Count} nested), {memberCount} members");
        }

        Console.WriteLine($"Total referenced: {methods.Count} methods, {fields.Count} fields.");
        return 0;
    }

    private static bool IsTarget(TypeDefinition t) => Targets.Contains(t.Module.Assembly.Name.Name);

    // ---- collection -------------------------------------------------------

    private static void AddNamespace(SortedSet<string> set, TypeReference tr)
    {
        if (tr == null) return;
        if (tr is TypeSpecification spec) { AddNamespace(set, spec.ElementType); return; }
        if (tr is GenericParameter) return;
        if (!string.IsNullOrEmpty(tr.Namespace) && !tr.Namespace.StartsWith("System", StringComparison.Ordinal))
            set.Add(tr.Namespace);
    }

    private static void Consider(TypeReference tr, HashSet<TypeDefinition> types,
        HashSet<MethodDefinition> methods, HashSet<FieldDefinition> fields, Queue<TypeDefinition> queue)
    {
        if (tr == null) return;
        if (tr is TypeSpecification spec)
        {
            Consider(spec.ElementType, types, methods, fields, queue);
            if (tr is GenericInstanceType git)
                foreach (var a in git.GenericArguments) Consider(a, types, methods, fields, queue);
            return;
        }
        if (tr is GenericParameter) return;

        var def = ResolveType(tr);
        if (def == null || !IsTarget(def)) return;
        if (types.Add(def)) queue.Enqueue(def);
    }

    private static void Consider(MethodReference mr, HashSet<TypeDefinition> types,
        HashSet<MethodDefinition> methods, HashSet<FieldDefinition> fields, Queue<TypeDefinition> queue)
    {
        if (mr == null) return;
        var def = ResolveMember(mr);
        if (def != null && IsTarget(def.DeclaringType))
        {
            Consider(def.DeclaringType, types, methods, fields, queue);
            methods.Add(def);
            Consider(def.ReturnType, types, methods, fields, queue);
            foreach (var p in def.Parameters) Consider(p.ParameterType, types, methods, fields, queue);
            return;
        }
        Consider(mr.DeclaringType, types, methods, fields, queue);
        Consider(mr.ReturnType, types, methods, fields, queue);
        foreach (var p in mr.Parameters) Consider(p.ParameterType, types, methods, fields, queue);
    }

    private static void Consider(FieldReference fr, HashSet<TypeDefinition> types,
        HashSet<MethodDefinition> methods, HashSet<FieldDefinition> fields, Queue<TypeDefinition> queue)
    {
        if (fr == null) return;
        var def = ResolveMember(fr);
        if (def != null && IsTarget(def.DeclaringType))
        {
            Consider(def.DeclaringType, types, methods, fields, queue);
            fields.Add(def);
        }
        Consider(fr.DeclaringType, types, methods, fields, queue);
        Consider(fr.FieldType, types, methods, fields, queue);
    }

    private static void WalkType(TypeDefinition type, HashSet<TypeDefinition> types,
        HashSet<MethodDefinition> methods, HashSet<FieldDefinition> fields)
    {
        var queue = new Queue<TypeDefinition>();
        Consider(type.BaseType, types, methods, fields, queue);
        foreach (var i in type.Interfaces) Consider(i.InterfaceType, types, methods, fields, queue);
        foreach (var f in type.Fields) Consider(f.FieldType, types, methods, fields, queue);
        foreach (var p in type.Properties)
        {
            Consider(p.PropertyType, types, methods, fields, queue);
            Consider(p.GetMethod, types, methods, fields, queue);
            Consider(p.SetMethod, types, methods, fields, queue);
        }
        foreach (var e in type.Events)
        {
            Consider(e.EventType, types, methods, fields, queue);
            Consider(e.AddMethod, types, methods, fields, queue);
            Consider(e.RemoveMethod, types, methods, fields, queue);
        }
        foreach (var m in type.Methods)
        {
            Consider(m.ReturnType, types, methods, fields, queue);
            foreach (var p in m.Parameters) Consider(p.ParameterType, types, methods, fields, queue);
            foreach (var gp in m.GenericParameters)
                foreach (var c in gp.Constraints) Consider(c.ConstraintType, types, methods, fields, queue);
            if (!m.HasBody) continue;
            foreach (var v in m.Body.Variables) Consider(v.VariableType, types, methods, fields, queue);
            foreach (var ins in m.Body.Instructions)
            {
                switch (ins.Operand)
                {
                    case MethodReference mref: Consider(mref, types, methods, fields, queue); break;
                    case FieldReference fref: Consider(fref, types, methods, fields, queue); break;
                    case TypeReference tref: Consider(tref, types, methods, fields, queue); break;
                }
            }
        }
        foreach (var nested in type.NestedTypes) WalkType(nested, types, methods, fields);
    }

    private static TypeDefinition ResolveType(TypeReference tr)
    {
        try { return tr?.Resolve(); } catch { return null; }
    }

    private static MethodDefinition ResolveMember(MethodReference mr)
    {
        try { return mr?.Resolve(); } catch { return null; }
    }

    private static FieldDefinition ResolveMember(FieldReference fr)
    {
        try { return fr?.Resolve(); } catch { return null; }
    }

    // ---- emission ---------------------------------------------------------

    private static void EmitTopLevel(StringBuilder sb, TypeDefinition t, HashSet<TypeDefinition> types,
        HashSet<MethodDefinition> methods, HashSet<FieldDefinition> fields)
    {
        if (string.IsNullOrEmpty(t.Namespace))
        {
            EmitBody(sb, t, types, methods, fields, 0);
            return;
        }

        sb.Append("namespace ").AppendLine(t.Namespace);
        sb.AppendLine("{");
        EmitBody(sb, t, types, methods, fields, 1);
        sb.AppendLine("}");
    }

    private static void EmitBody(StringBuilder sb, TypeDefinition t, HashSet<TypeDefinition> types,
        HashSet<MethodDefinition> methods, HashSet<FieldDefinition> fields, int depth)
    {
        var pad = new string(' ', depth * 4);
        var header = pad + Accessibility(t) + " ";

        if (t.IsEnum)
        {
            var underlying = t.Fields.FirstOrDefault(f => f.Name == "value__")?.FieldType;
            var suffix = underlying == null || underlying.FullName == "System.Int32" ? "" : " : " + Rend(underlying);
            sb.Append(header).Append("enum ").Append(CleanName(t.Name)).AppendLine(suffix);
            sb.Append(pad).AppendLine("{");
            var values = t.Fields.Where(f => f.IsLiteral && f.HasConstant).ToList();
            for (var i = 0; i < values.Count; i++)
            {
                sb.Append(pad).Append("    ").Append(values[i].Name).Append(" = ").Append(Literal(values[i].Constant));
                sb.AppendLine(i == values.Count - 1 ? "" : ",");
            }
            sb.Append(pad).AppendLine("}");
            return;
        }

        if (IsDelegate(t))
        {
            var invoke = t.Methods.First(m => m.Name == "Invoke");
            sb.Append(header).Append("delegate ").Append(Rend(invoke.ReturnType)).Append(' ')
              .Append(CleanName(t.Name)).Append('(')
              .Append(string.Join(", ", invoke.Parameters.Select(Param))).AppendLine(");");
            return;
        }

        sb.Append(header).Append(t.IsInterface ? "interface " : t.IsValueType ? "struct " : "class ")
          .Append(CleanName(t.Name));
        if (t.GenericParameters.Count > 0)
            sb.Append('<').Append(string.Join(", ", t.GenericParameters.Select(gp => gp.Name))).Append('>');

        var bases = new List<string>();
        if (t.BaseType != null && t.BaseType.FullName is not ("System.Object" or "System.ValueType"))
            bases.Add(Rend(t.BaseType));
        foreach (var i in t.Interfaces.Where(i => !i.InterfaceType.FullName.StartsWith("System.", StringComparison.Ordinal)))
            bases.Add(Rend(i.InterfaceType));
        if (bases.Count > 0) sb.Append(" : ").Append(string.Join(", ", bases));
        sb.AppendLine();
        sb.Append(pad).AppendLine("{");

        EmitMembers(sb, t, pad + "    ", methods, fields);

        foreach (var nested in t.NestedTypes.Where(types.Contains).OrderBy(n => n.Name, StringComparer.Ordinal))
            EmitBody(sb, nested, types, methods, fields, depth + 1);

        sb.Append(pad).AppendLine("}");
    }

    private static void EmitMembers(StringBuilder sb, TypeDefinition t, string inner,
        HashSet<MethodDefinition> methods, HashSet<FieldDefinition> fields)
    {
        foreach (var f in t.Fields.Where(f => fields.Contains(f) && !f.IsLiteral).OrderBy(f => f.Name, StringComparer.Ordinal))
        {
            sb.Append(inner).Append(Accessibility(f)).Append(' ');
            if (f.IsStatic) sb.Append("static ");
            if (f.IsInitOnly) sb.Append("readonly ");
            sb.Append(Rend(f.FieldType)).Append(' ').AppendLine(f.Name + ";");
        }

        var emitted = new HashSet<string>(StringComparer.Ordinal);
        foreach (var m in t.Methods.Where(methods.Contains).OrderBy(m => m.Name, StringComparer.Ordinal))
        {
            if (m.IsGetter || m.IsSetter)
            {
                var prop = t.Properties.FirstOrDefault(p => p.GetMethod == m || p.SetMethod == m);
                if (prop == null || !emitted.Add("P:" + prop.Name)) continue;
                EmitProperty(sb, prop, inner, methods);
                continue;
            }
            if (m.IsAddOn || m.IsRemoveOn || m.IsFire || m.Name == "Invoke") continue;
            if (m.IsConstructor)
            {
                sb.Append(inner).Append(Accessibility(m)).Append(' ').Append(CleanName(t.Name)).Append('(')
                  .Append(string.Join(", ", m.Parameters.Select(Param))).AppendLine(") { }");
                continue;
            }

            sb.Append(inner).Append(Accessibility(m)).Append(' ');
            if (m.IsStatic) sb.Append("static ");
            sb.Append(Rend(m.ReturnType)).Append(' ').Append(m.Name);
            if (m.GenericParameters.Count > 0)
                sb.Append('<').Append(string.Join(", ", m.GenericParameters.Select(gp => gp.Name))).Append('>');
            sb.Append('(').Append(string.Join(", ", m.Parameters.Select(Param))).Append(')');
            sb.AppendLine(m.ReturnType.FullName == "System.Void" ? " { }" : " => throw null;");
        }
    }

    private static void EmitProperty(StringBuilder sb, PropertyDefinition prop, string inner,
        HashSet<MethodDefinition> methods)
    {
        var accessor = prop.GetMethod ?? prop.SetMethod;
        sb.Append(inner).Append(Accessibility(accessor)).Append(' ');
        if (accessor.IsStatic) sb.Append("static ");
        sb.Append(Rend(prop.PropertyType)).Append(' ').Append(prop.Name);
        if (prop.HasParameters)
            sb.Append('[').Append(string.Join(", ", prop.Parameters.Select(p => Rend(p.ParameterType) + " " + p.Name))).Append(']');
        sb.Append(" { ");
        if (prop.GetMethod != null && methods.Contains(prop.GetMethod)) sb.Append("get; ");
        if (prop.SetMethod != null && methods.Contains(prop.SetMethod))
            sb.Append(prop.GetMethod != null && methods.Contains(prop.GetMethod) ? "set; " : "set { } ");
        sb.AppendLine("}");
    }

    private static bool IsDelegate(TypeDefinition t) =>
        t.BaseType != null && t.BaseType.FullName == "System.MulticastDelegate"
        && t.Methods.Any(m => m.Name == "Invoke");

    // Everything is declared public: the stubs exist purely so the plugin can be compiled on a
    // machine without the game, and the plugin carries [IgnoresAccessChecksTo] for the members
    // that are not public in the real assemblies.
    private static string Accessibility(TypeDefinition t) => "public";
    private static string Accessibility(MethodDefinition m) => "public";
    private static string Accessibility(FieldDefinition f) => "public";

    private static string CleanName(string name)
    {
        var tick = name.IndexOf('`');
        return tick < 0 ? name : name.Substring(0, tick);
    }

    private static string CleanFullName(TypeReference tr)
    {
        var parts = tr.FullName.Replace('/', '.').Split('.');
        for (var i = 0; i < parts.Length; i++) parts[i] = CleanName(parts[i]);
        return string.Join(".", parts);
    }

    private static readonly Dictionary<string, string> Keywords = new(StringComparer.Ordinal)
    {
        ["System.Void"] = "void",
        ["System.Boolean"] = "bool",
        ["System.Char"] = "char",
        ["System.SByte"] = "sbyte",
        ["System.Byte"] = "byte",
        ["System.Int16"] = "short",
        ["System.UInt16"] = "ushort",
        ["System.Int32"] = "int",
        ["System.UInt32"] = "uint",
        ["System.Int64"] = "long",
        ["System.UInt64"] = "ulong",
        ["System.Single"] = "float",
        ["System.Double"] = "double",
        ["System.Decimal"] = "decimal",
        ["System.String"] = "string",
        ["System.Object"] = "object",
    };

    private static string Rend(TypeReference tr)
    {
        switch (tr)
        {
            case null: return "object";
            case GenericParameter gp: return gp.Name;
            case ArrayType at: return Rend(at.ElementType) + "[" + new string(',', at.Rank - 1) + "]";
            case ByReferenceType br: return Rend(br.ElementType);
            case PointerType pt: return Rend(pt.ElementType) + "*";
            case GenericInstanceType git:
                return CleanFullName(git.ElementType) + "<" + string.Join(", ", git.GenericArguments.Select(Rend)) + ">";
            default:
                return Keywords.TryGetValue(tr.FullName, out var keyword) ? keyword : CleanFullName(tr);
        }
    }

    private static string Param(ParameterDefinition p)
    {
        if (p.CustomAttributes.Any(a => a.AttributeType.FullName == "System.ParamArrayAttribute"))
            return "params " + Rend(p.ParameterType) + " " + p.Name;
        var prefix = p.IsOut ? "out " : p.ParameterType.IsByReference ? "ref " : "";
        var fallback = p.HasConstant ? " = " + Literal(p.Constant) : "";
        return prefix + Rend(p.ParameterType) + " " + p.Name + fallback;
    }

    private static string Literal(object value) => value switch
    {
        null => "null",
        string s => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r").Replace("\n", "\\n") + "\"",
        bool b => b ? "true" : "false",
        char c => "'" + (c == '\'' ? "\\'" : c == '\\' ? "\\\\" : c.ToString()) + "'",
        float f when float.IsNaN(f) => "float.NaN",
        float f => f.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "f",
        double d when double.IsNaN(d) => "double.NaN",
        double d => d.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "d",
        IFormattable n => n.ToString(null, System.Globalization.CultureInfo.InvariantCulture),
        _ => value.ToString(),
    };

    private sealed class DefinitionComparer<T> : IEqualityComparer<T> where T : MemberReference
    {
        public static readonly DefinitionComparer<T> Instance = new();
        public bool Equals(T x, T y) =>
            ReferenceEquals(x, y) || (x != null && y != null && x.FullName == y.FullName && x.Module == y.Module);
        public int GetHashCode(T obj) => obj.FullName.GetHashCode();
    }
}
